def report_models(out: Path | None = None) -> Path:
    out = Path(out or REPORTS / "03_models.md")
    bundle = ModelBundle.load()
    m = bundle.metrics["sulfur_forecast"]
    dt = pd.DataFrame(bundle.metrics["deadtime"])
